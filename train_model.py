"""Train/validate an experimental route-agnostic traffic-delay model.

Run: python train_model.py [optional CSV path]
Outputs: model/traffic_model.js, model/metrics.json
The independent final test period is not used for model selection.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, root_mean_squared_error

from model_pipeline import FEATURE_NAMES, prepare_data, split_runs, features

ROOT = Path(__file__).resolve().parent


def report(y, p):
    return {'mae_seconds': round(float(mean_absolute_error(y,p)),2),
            'rmse_seconds': round(float(root_mean_squared_error(y,p)),2)}


def as_tree(tree):
    t = tree.tree_
    def go(node):
        if t.children_left[node] == t.children_right[node]:
            return round(float(t.value[node][0][0]),5)
        return [int(t.feature[node]), round(float(t.threshold[node]),5),
                go(int(t.children_left[node])), go(int(t.children_right[node]))]
    return go(0)


def run(csv_path=None):
    path = Path(csv_path) if csv_path else ROOT/'data'/'auto_collected.csv'
    df = prepare_data(pd.read_csv(path))
    train, val, test = split_runs(df)
    Xtrain, Xval, Xtest = map(features, [train,val,test])
    ytrain, yval, ytest = (x.delay_seconds.to_numpy() for x in (train,val,test))
    candidates = {
      'random_forest_depth4': dict(n_estimators=100,max_depth=4,min_samples_leaf=8),
      'random_forest_depth6': dict(n_estimators=100,max_depth=6,min_samples_leaf=8),
      'random_forest_depth8': dict(n_estimators=100,max_depth=8,min_samples_leaf=12),
    }
    evaluations = {'zero_delay':report(yval,np.zeros(len(yval)))}
    lr = LinearRegression().fit(Xtrain,ytrain)
    evaluations['linear_regression'] = report(yval,lr.predict(Xval))
    for name, params in candidates.items():
        rf = RandomForestRegressor(random_state=2277,n_jobs=-1,**params).fit(Xtrain,ytrain)
        evaluations[name] = report(yval,rf.predict(Xval))
    # Select between the linear model and forests; zero-delay is a comparison only.
    selected = min(['linear_regression',*candidates],key=lambda k:evaluations[k]['mae_seconds'])
    Xdev = pd.concat([Xtrain,Xval],ignore_index=True)
    ydev = np.concatenate([ytrain,yval])
    # The deployment model is always a real trained regressor, even if baseline outperforms it.
    if selected == 'linear_regression':
        model = LinearRegression().fit(Xdev,ydev)
        payload = {'type':'linear', 'coef':[round(float(v),9) for v in model.coef_],
                   'intercept':round(float(model.intercept_),9)}
    else:
        model = RandomForestRegressor(random_state=2277,n_jobs=-1,**candidates[selected]).fit(Xdev,ydev)
        payload = {'type':'forest', 'trees':[as_tree(t) for t in model.estimators_]}
    pred = model.predict(Xtest)
    metrics = {
      'version':1, 'data_file':str(path.name),'source_rows':int(len(df)),
      'source_route_count':int(df.route_id.nunique()),
      'source_route_ids':[int(x) for x in sorted(df.route_id.unique())],
      'date_start':str(df.collected_at.min()),'date_end':str(df.collected_at.max()),
      'collection_runs':int(df.collection_run.nunique()),
      'train_rows':int(len(train)),'validation_rows':int(len(val)),'test_rows':int(len(test)),
      'train_runs':int(train.collection_run.nunique()),'validation_runs':int(val.collection_run.nunique()),
      'test_runs':int(test.collection_run.nunique()),'validation':evaluations,'selected':selected,
      'test_zero_delay':report(ytest,np.zeros(len(ytest))),
      'test_selected':report(ytest,pred),
      'warning':'Test metrics cover historical routes only. No evidence of accuracy for new route IDs 16-50 or arbitrary origins/destinations.'
    }
    outdir = ROOT/'model';outdir.mkdir(exist_ok=True)
    model_data={'schema':1,'feature_names':FEATURE_NAMES,'model':payload,
                'data_routes':metrics['source_route_ids'],'trained_rows':int(len(df)),
                'test_mae_seconds':metrics['test_selected']['mae_seconds'],
                'selected':selected,'training_end':metrics['date_end']}
    # JS data file works both on GitHub Pages AND when opening HTML directly from disk.
    (outdir/'traffic_model.js').write_text('/* Generated by train_model.py. Do not hand-edit. */\n'+
      'globalThis.PINKMAP_TRAFFIC_MODEL = '+json.dumps(model_data,separators=(',',':'))+';\n',encoding='utf-8')
    (outdir/'metrics.json').write_text(json.dumps(metrics,indent=2)+'\n',encoding='utf-8')
    examples = [{'features':[float(x) for x in Xtest.iloc[i].tolist()],
                 'expected_delay_seconds':float(pred[i])}
                for i in [0, min(100,len(pred)-1), min(300,len(pred)-1)]]
    (outdir/'test_vectors.json').write_text(json.dumps({'examples':examples},indent=2)+'\n',encoding='utf-8')
    print(json.dumps(metrics,indent=2))
    return metrics

if __name__=='__main__':
    run(sys.argv[1] if len(sys.argv)>1 else None)
